func TestMigratedChannelCopsRunner(t *testing.T) {
	dir := t.TempDir()
	t.Chdir(dir)
	const src = `package p
import "context"
func concat(a, b []int) []int { return append(append([]int(nil), a...), b...) } // offense
func cancellation(ctx context.Context, ch chan int) { for { select { case <-ctx.Done(): continue; case <-ch: } } } // offense
func closed(ch chan int) { for { _, ok := <-ch; if !ok { continue } } } // offense
func state(ch chan int) { if len(ch) > 0 { <-ch } } // offense
func result(ctx context.Context) { ch := make(chan int); go func(){ ch <- 1 }(); select { case <-ctx.Done(): return; case <-ch: } } // offense
func replacement(ch chan int) { select { case ch <- 1: default: <-ch; ch <- 1 } } // offense
`
	checks := []struct {
		name      string
		testAware bool
	}{
		{"SlicesConcat", false},
		{"CancellationLoop", true},
		{"ClosedChannelLoop", true},
		{"ChannelStateCheck", true},
		{"CancellationSafeResultSend", false},
		{"NonblockingChannelReplacement", false},
	}
	var selected []prog.Cop
	var ids []string
	cfg := config.DefaultConfig()
	for _, check := range checks {
		id := "Lint/" + check.name
		selected = append(selected, registeredSharedCop(t, programCops, id))
		ids = append(ids, id)
		cfg.Cops[id] = config.CopConfig{Severity: "warning"}
		for _, c := range cops {
			assert.NotEqual(t, id, c.Name(), "must only be registered as a program cop")
		}
		count := 0
		for _, c := range programCops {
			if c.Name() == id {
				count++
			}
		}
		assert.Equal(t, 1, count, id)
	}

	var want []string
	files := make(map[string]string)
	for _, fixture := range []struct {
		dir, prefix string
		excluded    bool
	}{
		{dir: "reported"},
		{dir: "pkg/config/v0", excluded: true},
		{dir: "pkg/config/v15", excluded: true},
		{dir: "nested/pkg/config/v2", excluded: true},
		{dir: "pkg/config/latest"},
		{dir: "pkg/config/version"},
		{dir: "pkg/config/v1beta"},
		{dir: "notpkg/config/v0"},
		{dir: "generated", prefix: "// Code generated by fixture; DO NOT EDIT.\n", excluded: true},
		{dir: "inactive", prefix: "//go:build lint_fixture_disabled\n\n", excluded: true},
		{dir: "inline", excluded: true},
		{dir: "suppressed", prefix: "//rubocop:disable-file " + strings.Join(ids, ", ") + "\n", excluded: true},
		{dir: "external"},
		{dir: "testonly"},
		{dir: "illtyped"},
		{dir: "illtypedexternal"},
		{dir: "illtypedonly"},
	} {
		for _, filename := range []string{"sample.go", "sample_test.go"} {
			isTest := strings.HasSuffix(filename, "_test.go")
			content := src
			testsOnly := fixture.dir == "external" || fixture.dir == "testonly" || strings.HasPrefix(fixture.dir, "illtyped")
			if !isTest && testsOnly {
				if fixture.dir == "testonly" || fixture.dir == "illtypedonly" {
					continue
				}
				content = "package p\n"
			}
			if isTest {
				content = strings.ReplaceAll(content, "\nfunc ", "\nfunc test")
				if fixture.dir == "external" || fixture.dir == "illtypedexternal" {
					content = strings.Replace(content, "package p", "package p_test", 1)
				}
				if strings.HasPrefix(fixture.dir, "illtyped") {
					content += "\nvar _ = missing\n"
				}
			}
			if fixture.dir == "inline" {
				content = strings.ReplaceAll(content, "// offense", "//rubocop:disable "+strings.Join(ids, ", "))
			}
			path := fixture.dir + "/" + filename
			files[path] = fixture.prefix + content
			if fixture.excluded || (!isTest && testsOnly) {
				continue
			}
			for _, check := range checks {
				if !isTest || check.testAware {
					want = append(want, "Lint/"+check.name+":"+path)
				}
			}
		}
	}
	for path, content := range files {
		require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o700))
		require.NoError(t, os.WriteFile(path, []byte(content), 0o600))
	}

	for _, version := range []string{"1.21", "1.22", "1.27"} {
		t.Run(version, func(t *testing.T) {
			require.NoError(t, os.WriteFile("go.mod", []byte("module example.test\n\ngo "+version+"\n"), 0o600))
			var output bytes.Buffer
			r := runner.New(nil, cfg, &output).WithProgramCops(selected)
			r.Reporter = runner.NewJSONReporter(&output)
			count, err := r.Run([]string{"."})
			require.NoError(t, err)
			var expected []string
			for _, offense := range want {
				if version != "1.21" || !strings.HasPrefix(offense, "Lint/SlicesConcat:") {
					expected = append(expected, offense)
				}
			}
			assert.Equal(t, len(expected), count, output.String())
			var report struct {
				Offenses []struct{ Cop, File, Severity string }
			}
			require.NoError(t, json.Unmarshal(output.Bytes(), &report))
			var got []string
			for _, offense := range report.Offenses {
				assert.Equal(t, "warning", offense.Severity)
				path, err := filepath.Rel(dir, offense.File)
				require.NoError(t, err)
				got = append(got, offense.Cop+":"+filepath.ToSlash(path))
			}
			assert.ElementsMatch(t, expected, got)
			for path, content := range files {
				actual, err := os.ReadFile(path)
				require.NoError(t, err)
				assert.Equal(t, content, string(actual), path)
			}
		})
	}
}

func TestSharedStreamCloseSafetySliceBounds(t *testing.T) {
	t.Parallel()
	check := registeredSharedCop(t, programCops, "Lint/StreamCloseSafety")
	offenses := coptest.RunProgram(t, check, coptest.ProgramFiles{
		"stream.go": `package p
import "sync"
type stream struct { mu sync.Mutex; data []byte }
func (s *stream) Next() []byte { s.mu.Lock(); defer s.mu.Unlock(); return s.data[:] }
func (s *stream) Close() { s.mu.Lock(); defer s.mu.Unlock(); s.data = nil }
`,
	})
	assert.Empty(t, offenses)
}
